"""Thumbnail engine (owner 2026-11-12): many thumbnail designs, picked per video, never the same twice in a row.

Every design is drawn in code from real things only: the story's real logos (glossy or glass tiles), the
real pages the engine captured (curved, blurred), the source's own photo, and Goli in place of a person.
Nothing is generated by an image model.

1. Director: one small text call looks at the thumbnail of the video ours is modelled on, the title, the
   big words and what we have (logos, screenshots, photo), and ranks the designs that fit; it also names
   the mood. Designs used for the last videos are taken out first, so two in a row never match.
2. Each design is drawn; while it is drawn every word, logo, picture and Goli is recorded.
3. Layout check: words may not touch each other, logos, pictures or Goli; logos may not cover Goli's
   face or each other; words stay inside the frame. A design that fails is not used: the next one is drawn.
"""

