BY_NAME = {d.name: d for d in DESIGNS}

DIRECTOR_SCHEMA = {
    "type": "object", "additionalProperties": False, "required": ["ranking", "mood", "reason"],
    "properties": {
        "ranking": {"type": "array", "items": {"type": "string", "enum": [d.name for d in DESIGNS]}},
        "mood": {"type": "string", "enum": ["calm", "hype", "alarm", "money"]},
        "reason": {"type": "string"},
    },
}


def video_id(url: str) -> str | None:
    m = re.search(r"(?:v=|youtu\.be/|shorts/|embed/)([\w-]{11})", str(url or ""))
    return m.group(1) if m else None


def direct(text, s: Story, model_url: str, model_title: str, choices: list[Design]) -> tuple[list[str], str, str]:
    """One small call: which designs fit this video, closest to the thumbnail of the video it is modelled on."""
    vid = video_id(model_url)
    images = [f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg"] if vid else None
    menu = "\n".join(f"- {d.name}: {d.about}" for d in choices)
    out = text.generate_json(
        "You art-direct a YouTube thumbnail for a tech channel whose host is a mascot (Goli, a pangolin). "
        "Look at the thumbnail of the video ours is modelled on (if given) and the story, then rank the designs "
        "below from best to worst fit: the closest in idea and composition to the model thumbnail first, then by "
        "what the story is about. Use only designs from the list. Also give the mood of the story.",
        f"OUR TITLE: {s.title}\nBIG WORDS: {s.words} (accent: {s.punch})\nLOGOS WE HAVE: {', '.join(s.names) or 'none'}\n"
        f"REAL PAGE SCREENSHOTS: {len(s.shots)}\nSOURCE PHOTO: {'yes' if s.photo else 'no'}\n"
        f"MODEL VIDEO TITLE: {model_title or 'unknown'}\n\nDESIGNS:\n{menu}",
        DIRECTOR_SCHEMA, max_output_tokens=800, images=images)
    v = out.value
    return [n for n in v.get("ranking", []) if n in BY_NAME], str(v.get("mood", "calm")), str(v.get("reason", ""))


def recent_designs(root: Path, limit: int = 3) -> list[str]:
    """Designs used by the last long videos (newest first), from the production records."""
    rows = []
    for path in (root / "data" / "production-records").glob("*.json"):
        try:
            r = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        style = ((r.get("generation_parameters") or {}) if isinstance(r.get("generation_parameters"), dict) else {}).get(
            "thumbnail_style")
        if style:
            rows.append((str(r.get("recorded_at", "")), style))
    return [s for _, s in sorted(rows, reverse=True)[:limit]]


def render(design: Design, s: Story) -> tuple[Image.Image, list[str]]:
    drawn = design.draw(s)
    if isinstance(drawn, str):
        image, hits = shoot(drawn)
        return finish(image), hits
    return finish(drawn), (fill_check(T.REC) if T.REC is not None else [])


def make(title: str, words: str, punch: str, brands: list[str], out: Path, *, shots: list[Path] | None = None,
         photo: Path | None = None, outfit: str = "royal", recent: list[str] | None = None, text=None,
         model_url: str = "", model_title: str = "", seed: int = 0, log: Callable[[dict], None] = print) -> str:
    """Draw the thumbnail; returns the design used. Never the design of the last videos; never with a collision."""
    found = [(b, logos.find(b)) for b in brands]
    found = [(b, i) for b, i in found if i][:7]
    s = Story(title, " ".join(str(words).split()).upper(), str(punch).strip().upper(), [b for b, _ in found],
              [i for _, i in found], [p for p in (shots or []) if Path(p).exists()],
              photo if photo and Path(photo).exists() else None, outfit, "alarm" if T.is_alert(title + " " + words) else "calm",
              seed)
    if not s.punch or s.punch not in s.words:
        s.punch = s.words.split()[-1] if s.words else ""
    recent = recent or []
    fit = [d for d in DESIGNS if d.fits(s)]
    choices = [d for d in fit if d.name not in recent[:2]] or fit          # never the last two again
    ranking: list[str] = []
    if text is not None:
        try:
            ranking, mood, reason = direct(text, s, model_url, model_title, choices)
            s.mood = "alarm" if s.mood == "alarm" else mood
            log({"status": "thumbnail_director", "ranking": ranking[:5], "mood": s.mood, "reason": reason[:200]})
        except Exception as exc:  # noqa: BLE001 - the designs still rank by the story without the director
            log({"status": "thumbnail_director_failed", "error": str(exc)[:200]})
    rnd = random.Random(seed)
    rest = [d.name for d in choices if d.name not in ranking]
    rnd.shuffle(rest)
    order = [n for n in ranking if n in {d.name for d in choices}] + rest
    best: tuple[int, str, Image.Image] | None = None
    for name in order[:6]:
        T.REC = []
        try:
            image, hits = render(BY_NAME[name], s)
            hits = hits + check(T.REC)
        except Exception as exc:  # noqa: BLE001 - one design failing never stops the thumbnail
            log({"status": "thumbnail_design_failed", "design": name, "error": str(exc)[:200]})
            continue
        finally:
            T.REC = None
        log({"status": "thumbnail_layout_check", "design": name, "collisions": hits[:6]})
        if not hits:
            image.convert("RGB").save(out, quality=92)
            return name
        if best is None or len(hits) < best[0]:
            best = (len(hits), name, image)
    if best is None:
        raise RuntimeError("no thumbnail design could be drawn")
    best[2].convert("RGB").save(out, quality=92)
    return best[1]
