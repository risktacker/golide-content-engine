    for col, base in (((30, 44, 58), 330), ((22, 32, 42), 420), ((14, 20, 28), 520)):
        pts, x = [(0, H)], 0
        while x <= W:
            pts.append((x, base + rnd.randint(-60, 40)))
            x += rnd.randint(40, 110)
