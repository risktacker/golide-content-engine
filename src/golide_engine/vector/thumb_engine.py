QA_JS = r"""() => {
  const els = [...document.querySelectorAll('[data-qa]')].map((e, i) => {
    const r = e.getBoundingClientRect();
    return {kind: e.dataset.qa, i, x: r.left, y: r.top, w: r.width, h: r.height};
  });
  const ok = ['face+title','shot+title','tile+title','title+title','tile+tile','face+tile','body+title','body+tile'];
  const hits = [];
  for (let i = 0; i < els.length; i++) {
    const a = els[i];
    if (['title','tile'].includes(a.kind) && (a.x < 6 || a.y < 4 || a.x + a.w > 1274 || a.y + a.h > 716))
      hits.push(`${a.kind} #${a.i} leaves the frame`);
    for (let j = i + 1; j < els.length; j++) {
      const b = els[j];
      if (!ok.includes([a.kind, b.kind].sort().join('+'))) continue;
      const w = Math.min(a.x + a.w, b.x + b.w) - Math.max(a.x, b.x), h = Math.min(a.y + a.h, b.y + b.h) - Math.max(a.y, b.y);
      if (w > 2 && h > 2) hits.push(`${a.kind} #${a.i} x ${b.kind} #${b.i}`);
    }
  }
  return hits;
}"""


