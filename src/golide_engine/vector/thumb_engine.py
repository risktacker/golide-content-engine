def _uri(img_or_path, kind="png") -> str:
    if isinstance(img_or_path, Image.Image):
        buf = io.BytesIO()
        img_or_path.save(buf, "PNG")
        data = buf.getvalue()
    else:
        p = Path(img_or_path)
        im = Image.open(p).convert("RGB")
        im.thumbnail((1400, 1400))
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=86)
        data, kind = buf.getvalue(), "jpeg"
    return f"data:image/{kind};base64," + base64.b64encode(data).decode()


def _font_uri(name: str) -> str:
    kind = "otf" if name.endswith(".otf") else "woff"
    return f"data:font/{kind};base64," + base64.b64encode((FONTS / name).read_bytes()).decode()


def _glass(icon: dict, size: int, x: int, y: int, rot: float = 0) -> str:
    svg = icon["svg"].replace("<svg ", f'<svg fill="#{icon["hex"]}" width="{size * .52}" height="{size * .52}" ', 1)
    return (f'<div class="glass" data-qa="tile" style="left:{x}px;top:{y}px;width:{size}px;height:{size}px;'
            f'transform:rotate({rot}deg)">{svg}</div>')


def _shot(src: str, x, y, w, ry, blur, z=0, origin="center") -> str:
    return (f'<div class="shot" data-qa="shot" style="left:{x}px;top:{y}px;width:{w}px;'
            f'transform:perspective(1100px) rotateY({ry}deg) translateZ({z}px);transform-origin:{origin};'
            f'filter:blur({blur}px)"><img src="{src}"></div>')


def _box(div: str, box, x: int, y: int, pad: int = 6) -> str:
    l, t, r, btm = box
    return (f'<div data-qa="{div}" style="position:absolute;left:{x + l - pad}px;top:{y + t - pad}px;'
            f'width:{r - l + 2 * pad}px;height:{btm - t + 2 * pad}px"></div>')


def _goli_html(cut: Image.Image, cx: float, bottom: float) -> str:
    """Goli plus his measured head and body boxes (taken from the drawing itself, not guessed)."""
    x, y = int(cx - cut.width / 2), int(bottom - cut.height)
    a = cut.getchannel("A")
    head = a.crop((0, 0, a.width, int(a.height * .46))).getbbox() or (0, 0, 1, 1)
    trunk = a.crop((int(a.width * .2), int(a.height * .46), int(a.width * .8), a.height)).getbbox() or (0, 0, 1, 1)
    trunk = (trunk[0] + int(a.width * .2), trunk[1] + int(a.height * .46), trunk[2] + int(a.width * .2),
             trunk[3] + int(a.height * .46))
    return (f'<img data-qa="goli" src="{_uri(cut)}" style="position:absolute;left:{x}px;top:{y}px;width:{cut.width}px">'
            + _box("face", head, x, y) + _box("body", trunk, x, y, 0))


