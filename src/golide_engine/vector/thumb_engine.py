@dataclass
class Story:
    title: str
    words: str
    punch: str
    names: list[str] = field(default_factory=list)
    icons: list[dict] = field(default_factory=list)
    shots: list[Path] = field(default_factory=list)       # real page screenshots (faces already blurred)
    photo: Path | None = None
    outfit: str = "royal"
    mood: str = "calm"                                     # calm | hype | alarm | money
    seed: int = 0

    @property
    def rest(self) -> str:
        w, p = " ".join(self.words.split()), self.punch.strip()
        r = " ".join(w.replace(p, " ").split()) if p and p in w else w
        return r or w

    @property
    def accent(self) -> tuple[int, int, int]:
        if self.mood == "alarm":
            return (236, 52, 46)
        return T._vivid(T._hex(self.icons[0]["hex"])) if self.icons else (124, 58, 255)


# ---------------------------------------------------------------- layout check

PAIRS = {("text", "text"), ("text", "tile"), ("text", "face"), ("text", "goli"), ("text", "picture"),
         ("face", "tile"), ("tile", "tile"), ("face", "picture")}


def check(rec: list[tuple[str, Image.Image]], allow: int = 25) -> list[str]:
    hits = []
    for i, (ka, ma) in enumerate(rec):
        if ka == "text":
            box = ma.getbbox()
            if box and (box[0] < 6 or box[1] < 4 or box[2] > W - 6 or box[3] > H - 4):
                hits.append(f"words #{i} leave the frame")
        for j in range(i + 1, len(rec)):
            kb, mb = rec[j]
            if tuple(sorted((ka, kb))) not in PAIRS:
                continue
            if ka == kb == "face":
                continue
            # words keep a clear margin (about 7 px) from everything else
            a2 = ma.filter(ImageFilter.MaxFilter(15)) if ka == "text" and kb != "text" else ma
            b2 = mb.filter(ImageFilter.MaxFilter(15)) if kb == "text" and ka != "text" else mb
            both = ImageChops.multiply(a2, b2)
            n = both.histogram()[255]
            if n > (4 if "text" in (ka, kb) else allow):      # words: not one pixel more than a speck
                hits.append(f"{ka} #{i} x {kb} #{j} ({n} px)")
    return hits


def _put_goli(b: Image.Image, cut: Image.Image, cx: float, bottom: float, rim=None) -> None:
    if rim:
        cut = T._rim(cut, rim)
    xy = (int(cx - cut.width / 2), int(bottom - cut.height))
    b.alpha_composite(cut, xy)
    T.record_goli(cut, xy)


def _shadow(b, cx, y, w, a=110, blur=22):
    s = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(s).ellipse([cx - w / 2, y - 22, cx + w / 2, y + 22], fill=(0, 0, 0, a))
    b.alpha_composite(s.filter(ImageFilter.GaussianBlur(blur)))


def _tiles(items: list[dict], w: int, h: int, dist: float, **kw) -> Image.Image:
    return T.render_tiles(dict({"w": w, "h": h, "fov": 30, "dist": dist, "items": items}, **kw))


def paw(r: float) -> Image.Image:
    """Goli's paw (the SVG's colours): round, lit from the top left, three dark claws."""
    im = Image.new("RGBA", (int(r * 2.4), int(r * 2.6)), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    cx, cy = im.width / 2, r * 1.1
    for k in range(int(r), 0, -1):
        t = k / r
        col = tuple(int(a + (c - a) * t) for a, c in zip((255, 233, 200), (217, 154, 85)))
        d.ellipse([cx - k - (r - k) * .2, cy - k - (r - k) * .3, cx + k - (r - k) * .2, cy + k - (r - k) * .3], fill=col)
    for dx in (-r * .55, 0, r * .55):
        d.polygon([(cx + dx - r * .16, cy + r * .72), (cx + dx, cy + r * 1.35), (cx + dx + r * .16, cy + r * .72)],
                  fill=(58, 36, 22))
    sh = Image.new("RGBA", im.size, (0, 0, 0, 0))
    sh.putalpha(im.getchannel("A").point(lambda v: int(v * .45)))
    out = Image.new("RGBA", (im.width + 12, im.height + 16), (0, 0, 0, 0))
    out.alpha_composite(sh.filter(ImageFilter.GaussianBlur(6)), (6, 12))
    out.alpha_composite(im, (6, 0))
    return out


def sleeve(b, a, z, w, outfit: str) -> None:
    """A hoodie arm from a to z in the day's outfit colours, with the cuff at the wrist."""
    from ..edit.mascot import OUTFITS
    o = OUTFITS.get(outfit) or next(iter(OUTFITS.values()))
    main, light, cuff = (T._hex(o[k].lstrip("#")) for k in ("main", "shine", "deep"))
    d = ImageDraw.Draw(b)
    d.line([a, z], fill=main, width=int(w))
    d.ellipse([a[0] - w / 2, a[1] - w / 2, a[0] + w / 2, a[1] + w / 2], fill=main)
    d.line([(a[0], a[1] - w * .25), (z[0], z[1] - w * .25)], fill=light, width=int(w * .18))
    ux, uy = z[0] - a[0], z[1] - a[1]
    n = math.hypot(ux, uy) or 1
    d.line([(z[0] - ux / n * w * .35, z[1] - uy / n * w * .35), z], fill=cuff, width=int(w * 1.04))


def _pose(s: Story, calm="sure", hype="happy", alarm="shock", money="happy") -> str:
    return {"calm": calm, "hype": hype, "alarm": alarm, "money": money}.get(s.mood, calm)


