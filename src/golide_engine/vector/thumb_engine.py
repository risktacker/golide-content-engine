def _legacy(style: str) -> Callable[[Story], Image.Image]:
    """The 2026-11-10 styles, with Goli (thumb_styles.compose)."""
    def draw(s: Story) -> Image.Image:
        pose, mouth, expression, _, height = T.GOLI[style]
        if style in ("dark_drama", "photo_card") or s.mood == "alarm":
            pose, mouth, expression = "shock", "E", "shock"
        host = T.goli(pose, s.outfit, mouth, expression, height)
        out = Path(f"/tmp/golide-thumb-{style}-{s.seed}.png")
        screen = s.photo or (s.shots[0] if s.shots else None)
        T.compose(style, s.words, s.punch, s.names[:6 if style == "platter" else 3], s.icons[:6 if style == "platter" else 3],
                  out, host=host, photo=screen if style in ("photo_card", "studio") else None)
        img = Image.open(out).convert("RGBA")
        out.unlink(missing_ok=True)
        return img
    return draw


